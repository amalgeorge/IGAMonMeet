#!/usr/bin/env python3
"""Builds db/mssql/igamonmeet-schema.sql: every Flyway migration for SQL Server in one script a DBA can run.

The script creates the schema and fills flyway_schema_history exactly as Flyway would (same versions, descriptions
and checksums), so when the app starts against that database Flyway sees everything applied and only runs newer
migrations. CI runs it against SQL Server and then starts Flyway on the result (job migrations-mssql).


It also builds db/mssql/igamonmeet-upgrade.sql: brings an existing database to the current version, applying only the
migrations its flyway_schema_history does not list yet (safe to run again).

  python3 tools/db/build_mssql_script.py                    write both scripts
  python3 tools/db/build_mssql_script.py --check            fail if a checked-in script is out of date
  python3 tools/db/build_mssql_script.py --upto 20 FILE     write a schema script that stops at version 20 (CI uses it
                                                            to test the upgrade script against an older database)
"""
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = [ROOT / "src/main/resources/db/migration", ROOT / "src/main/resources/db/vendor/sqlserver"]
OUT = ROOT / "db/mssql/igamonmeet-schema.sql"
UPGRADE = ROOT / "db/mssql/igamonmeet-upgrade.sql"
PLACEHOLDERS = {"longText": "NVARCHAR(MAX)", "longBinary": "VARBINARY(MAX)"}  # application.yml spring.flyway.placeholders
NAME = re.compile(r"^V(\d+(?:_\d+)*)__(.+)\.sql$")


def migrations():
    found = []
    for d in SOURCES:
        for f in d.glob("V*.sql"):
            m = NAME.match(f.name)
            if not m:
                raise SystemExit(f"Unexpected migration name: {f.name}")
            version = m.group(1).replace("_", ".")
            found.append((tuple(int(p) for p in version.split(".")), version, m.group(2).replace("_", " "), f))
    found.sort(key=lambda x: x[0])
    return found


def checksum(path):
    """Flyway's checksum: CRC32 over the UTF-8 bytes of each line, line breaks removed, BOM stripped from line 1."""
    crc = 0
    text = path.read_bytes().decode("utf-8")
    lines = re.split(r"\r\n|\r|\n", text)
    if lines and lines[-1] == "":
        lines.pop()  # readLine() returns no empty line after a final line break
    for i, line in enumerate(lines):
        if i == 0:
            line = line.lstrip("﻿")
        crc = zlib.crc32(line.encode("utf-8"), crc)
    return crc - (1 << 32) if crc >= (1 << 31) else crc  # Java int


def batches(sql):
    """GO-separated batches: one per statement, so a later statement can use a column an earlier one added.
    Procedures and triggers stay whole (their bodies contain semicolons)."""
    if re.search(r"(?im)^\s*CREATE\s+(OR\s+ALTER\s+)?(PROCEDURE|PROC|TRIGGER|FUNCTION|VIEW)\b", sql):
        return [sql.strip()]
    out, cur = [], []
    for line in sql.splitlines():
        cur.append(line)
        code = line.split("--", 1)[0].rstrip()
        if code.endswith(";"):
            out.append("\n".join(cur).strip())
            cur = []
    rest = "\n".join(cur).strip()
    if rest and any(l.split("--", 1)[0].strip() for l in rest.splitlines()):
        out.append(rest)
    elif rest and out:
        out[-1] += "\n" + rest
    return [b for b in out if b]


SET_OPTIONS = """SET NOCOUNT ON;
SET XACT_ABORT ON;
-- sqlcmd starts with QUOTED_IDENTIFIER OFF; filtered indexes and the procedure need the settings the JDBC driver uses.
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET NUMERIC_ROUNDABORT OFF;
GO
"""


def resolved(f):
    """The migration's SQL with the Flyway placeholders filled in."""
    sql = f.read_text(encoding="utf-8").lstrip("﻿")
    for k, v in PLACEHOLDERS.items():
        sql = sql.replace("${" + k + "}", v)
    if "${" in sql:
        raise SystemExit(f"Unknown placeholder in {f.name}")
    return sql


def build_upgrade():
    """Per migration: skipped when its version is in the history, else applied in one transaction with its history row.
    Statements run through EXEC so a skipped migration is never compiled against a newer schema, and #upgrade_stop
    halts everything after a failure even when sqlcmd runs without -b."""
    ms = migrations()
    last = ms[-1][1]
    history = "dbo.flyway_schema_history"
    parts = [f"""-- =====================================================================================================
-- IAM Monthly Meeting: SQL Server UPGRADE script, to schema version {last}
-- Generated by tools/db/build_mssql_script.py from the Flyway migrations. Do not edit by hand.
--
-- Run on an EXISTING app database (made by igamonmeet-schema.sql or by the app), with the app stopped and a
-- backup taken, as a login that can change tables, triggers and procedures (e.g. db_owner):
--   sqlcmd -S <server> -d igamonmeet -E -b -i igamonmeet-upgrade.sql
--
-- It applies only the migrations {history} does not list yet. Each one runs in its own
-- transaction together with its history row, so a failure leaves that migration fully undone and stops the
-- script. Running it again changes nothing. See db/mssql/README.md.
-- =====================================================================================================
""", SET_OPTIONS, f"""IF OBJECT_ID(N'tempdb..#upgrade_stop') IS NOT NULL DROP TABLE #upgrade_stop;
CREATE TABLE #upgrade_stop (reason NVARCHAR(200) NOT NULL);
GO
IF OBJECT_ID(N'{history}', N'U') IS NULL
BEGIN
    INSERT INTO #upgrade_stop VALUES (N'no Flyway history');
    RAISERROR('No Flyway history in this database: create it with igamonmeet-schema.sql instead.', 16, 1);
END
GO
IF EXISTS (SELECT 1 FROM {history} WHERE success = 0)
BEGIN
    INSERT INTO #upgrade_stop VALUES (N'failed migration in history');
    RAISERROR('The Flyway history has a failed migration: have it repaired before upgrading.', 16, 1);
END
GO

"""]
    for _, version, desc, f in ms:
        esc = desc.replace("'", "''")
        parts.append(f"""-- ---- V{version}: {desc} ({f.relative_to(ROOT)}) ----
IF NOT EXISTS (SELECT 1 FROM #upgrade_stop) AND NOT EXISTS (SELECT 1 FROM {history} WHERE version = N'{version}')
    BEGIN TRANSACTION;
GO
""")
        for b in batches(resolved(f)):
            if re.search(r"(?im)^\s*GO\s*$", b):
                raise SystemExit(f"{f.name} has a GO line: not supported")
            parts.append("IF @@TRANCOUNT > 0 EXEC(N'\n" + b.replace("'", "''") + "\n');\nGO\n")
        parts.append(f"""IF @@TRANCOUNT > 0
BEGIN
    INSERT INTO {history} (installed_rank, version, description, type, script, checksum, installed_by, execution_time, success)
    SELECT ISNULL(MAX(installed_rank), 0) + 1, N'{version}', N'{esc}', N'SQL', N'{f.name}', {checksum(f)}, SUSER_SNAME(), 0, 1
    FROM {history};
    COMMIT TRANSACTION;
    PRINT 'Applied V{version}: {esc}';
END
ELSE IF NOT EXISTS (SELECT 1 FROM #upgrade_stop) AND NOT EXISTS (SELECT 1 FROM {history} WHERE version = N'{version}')
BEGIN
    INSERT INTO #upgrade_stop VALUES (N'V{version} failed');
    RAISERROR('V{version} failed and was rolled back. Nothing after it was applied.', 16, 1);
END
GO

""")
    parts.append(f"""IF EXISTS (SELECT 1 FROM #upgrade_stop)
    RAISERROR('Upgrade stopped: see the first error above.', 16, 1);
ELSE
    PRINT 'IAM Monthly Meeting database is at schema version {last}.';
GO
DROP TABLE #upgrade_stop;
GO
""")
    return "".join(parts)


def build(upto=None):
    """The full schema script; upto stops at that version (CI builds an older database with it)."""
    ms = migrations()
    if upto is not None:
        limit = tuple(int(p) for p in upto.split("."))
        ms = [m for m in ms if m[0] <= limit]
    last = ms[-1][1]
    parts = [f"""-- =====================================================================================================
-- IAM Monthly Meeting: SQL Server database script, schema version {last}
-- Generated by tools/db/build_mssql_script.py from the Flyway migrations. Do not edit by hand.
--
-- Run on an EMPTY database, as a login that can create tables, triggers and procedures (e.g. db_owner):
--   sqlcmd -S <server> -d igamonmeet -E -b -i igamonmeet-schema.sql
-- See db/mssql/README.md for the login, permissions and the first Admin.
--
-- The last part fills dbo.flyway_schema_history the way Flyway does, so the app treats every migration up to
-- version {last} as applied and runs only newer ones at start-up.
-- =====================================================================================================
""" + SET_OPTIONS + """IF OBJECT_ID(N'dbo.flyway_schema_history', N'U') IS NOT NULL
    THROW 50001, 'This database already has a Flyway history: use the upgrade path in db/mssql/README.md instead.', 1;
GO
"""]
    for _, version, desc, f in ms:
        sql = resolved(f)
        parts.append(f"-- ---- V{version}: {desc} ({f.relative_to(ROOT)}) ----\n")
        for b in batches(sql):
            parts.append(b + "\nGO\n")
        parts.append("\n")
    parts.append("""-- ---- Flyway history (same table Flyway 8 creates) ----
CREATE TABLE dbo.flyway_schema_history (
    installed_rank INT NOT NULL,
    version NVARCHAR(50),
    description NVARCHAR(200),
    type NVARCHAR(20) NOT NULL,
    script NVARCHAR(1000) NOT NULL,
    checksum INT,
    installed_by NVARCHAR(100) NOT NULL,
    installed_on DATETIME NOT NULL DEFAULT GETDATE(),
    execution_time INT NOT NULL,
    success BIT NOT NULL,
    CONSTRAINT flyway_schema_history_pk PRIMARY KEY (installed_rank)
);
GO
CREATE INDEX flyway_schema_history_s_idx ON dbo.flyway_schema_history (success);
GO
""")
    rows = []
    for rank, (_, version, desc, f) in enumerate(ms, start=1):
        rows.append(f"    ({rank}, N'{version}', N'{desc.replace(chr(39), chr(39) * 2)}', N'SQL', N'{f.name}', {checksum(f)}, SUSER_SNAME(), 0, 1)")
    parts.append("INSERT INTO dbo.flyway_schema_history (installed_rank, version, description, type, script, checksum, installed_by, execution_time, success) VALUES\n")
    parts.append(",\n".join(rows) + ";\nGO\n")
    parts.append(f"PRINT 'IAM Monthly Meeting schema version {last} created.';\nGO\n")
    return "".join(parts)


if __name__ == "__main__":
    if "--upto" in sys.argv:
        i = sys.argv.index("--upto")
        Path(sys.argv[i + 2]).write_text(build(sys.argv[i + 1]), encoding="utf-8", newline="\n")
        print(f"Wrote the schema up to version {sys.argv[i + 1]} to {sys.argv[i + 2]}")
        sys.exit(0)
    outputs = [(OUT, build()), (UPGRADE, build_upgrade())]
    for path, text in outputs:
        name = path.relative_to(ROOT)
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"{name} is out of date: run python3 tools/db/build_mssql_script.py and commit it.")
            print(f"{name} is up to date.")
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"Wrote {name}")
