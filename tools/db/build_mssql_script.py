#!/usr/bin/env python3
"""Builds db/mssql/igamonmeet-schema.sql: every Flyway migration for SQL Server in one script a DBA can run.

The script creates the schema and fills flyway_schema_history exactly as Flyway would (same versions, descriptions
and checksums), so when the app starts against that database Flyway sees everything applied and only runs newer
migrations. CI runs it against SQL Server and then starts Flyway on the result (job migrations-mssql).

  python3 tools/db/build_mssql_script.py           write the script
  python3 tools/db/build_mssql_script.py --check   fail if the checked-in script is out of date
"""
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = [ROOT / "src/main/resources/db/migration", ROOT / "src/main/resources/db/vendor/sqlserver"]
OUT = ROOT / "db/mssql/igamonmeet-schema.sql"
PLACEHOLDERS = {"longText": "NVARCHAR(MAX)", "longBinary": "VARBINARY(MAX)"}  # application.yml spring.flyway.placeholders
NAME = re.compile(r"^V(\d+(?:_\d+)*)__(.+)\.sql$")


def migrations():
    found = []
    for d in SOURCES:
        for f in d.glob("V*.sql"):
            m = NAME.match(f.name)
            if not m:
                raise SystemExit(f"Unexpected migration name: {f.name}")
            version = m.group(1).replace("_", ".")
            found.append((tuple(int(p) for p in version.split(".")), version, m.group(2).replace("_", " "), f))
    found.sort(key=lambda x: x[0])
    return found


def checksum(path):
    """Flyway's checksum: CRC32 over the UTF-8 bytes of each line, line breaks removed, BOM stripped from line 1."""
    crc = 0
    text = path.read_bytes().decode("utf-8")
    lines = re.split(r"\r\n|\r|\n", text)
    if lines and lines[-1] == "":
        lines.pop()  # readLine() returns no empty line after a final line break
    for i, line in enumerate(lines):
        if i == 0:
            line = line.lstrip("﻿")
        crc = zlib.crc32(line.encode("utf-8"), crc)
    return crc - (1 << 32) if crc >= (1 << 31) else crc  # Java int


def batches(sql):
    """GO-separated batches: one per statement, so a later statement can use a column an earlier one added.
    Procedures and triggers stay whole (their bodies contain semicolons)."""
    if re.search(r"(?im)^\s*CREATE\s+(OR\s+ALTER\s+)?(PROCEDURE|PROC|TRIGGER|FUNCTION|VIEW)\b", sql):
        return [sql.strip()]
    out, cur = [], []
    for line in sql.splitlines():
        cur.append(line)
        code = line.split("--", 1)[0].rstrip()
        if code.endswith(";"):
            out.append("\n".join(cur).strip())
            cur = []
    rest = "\n".join(cur).strip()
    if rest and any(l.split("--", 1)[0].strip() for l in rest.splitlines()):
        out.append(rest)
    elif rest and out:
        out[-1] += "\n" + rest
    return [b for b in out if b]


def build():
    ms = migrations()
    last = ms[-1][1]
    parts = [f"""-- =====================================================================================================
-- IAM Monthly Meeting: SQL Server database script, schema version {last}
-- Generated by tools/db/build_mssql_script.py from the Flyway migrations. Do not edit by hand.
--
-- Run on an EMPTY database, as a login that can create tables, triggers and procedures (e.g. db_owner):
--   sqlcmd -S <server> -d igamonmeet -E -b -i igamonmeet-schema.sql
-- See db/mssql/README.md for the login, permissions and the first Admin.
--
-- The last part fills dbo.flyway_schema_history the way Flyway does, so the app treats every migration up to
-- version {last} as applied and runs only newer ones at start-up.
-- =====================================================================================================
SET NOCOUNT ON;
SET XACT_ABORT ON;
-- sqlcmd starts with QUOTED_IDENTIFIER OFF; filtered indexes and the procedure need the settings the JDBC driver uses.
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET NUMERIC_ROUNDABORT OFF;
GO
IF OBJECT_ID(N'dbo.flyway_schema_history', N'U') IS NOT NULL
    THROW 50001, 'This database already has a Flyway history: use the upgrade path in db/mssql/README.md instead.', 1;
GO
"""]
    for _, version, desc, f in ms:
        sql = f.read_text(encoding="utf-8").lstrip("﻿")
        for k, v in PLACEHOLDERS.items():
            sql = sql.replace("${" + k + "}", v)
        if "${" in sql:
            raise SystemExit(f"Unknown placeholder in {f.name}")
        parts.append(f"-- ---- V{version}: {desc} ({f.relative_to(ROOT)}) ----\n")
        for b in batches(sql):
            parts.append(b + "\nGO\n")
        parts.append("\n")
    parts.append("""-- ---- Flyway history (same table Flyway 8 creates) ----
CREATE TABLE dbo.flyway_schema_history (
    installed_rank INT NOT NULL,
    version NVARCHAR(50),
    description NVARCHAR(200),
    type NVARCHAR(20) NOT NULL,
    script NVARCHAR(1000) NOT NULL,
    checksum INT,
    installed_by NVARCHAR(100) NOT NULL,
    installed_on DATETIME NOT NULL DEFAULT GETDATE(),
    execution_time INT NOT NULL,
    success BIT NOT NULL,
    CONSTRAINT flyway_schema_history_pk PRIMARY KEY (installed_rank)
);
GO
CREATE INDEX flyway_schema_history_s_idx ON dbo.flyway_schema_history (success);
GO
""")
    rows = []
    for rank, (_, version, desc, f) in enumerate(ms, start=1):
        rows.append(f"    ({rank}, N'{version}', N'{desc.replace(chr(39), chr(39) * 2)}', N'SQL', N'{f.name}', {checksum(f)}, SUSER_SNAME(), 0, 1)")
    parts.append("INSERT INTO dbo.flyway_schema_history (installed_rank, version, description, type, script, checksum, installed_by, execution_time, success) VALUES\n")
    parts.append(",\n".join(rows) + ";\nGO\n")
    parts.append(f"PRINT 'IAM Monthly Meeting schema version {last} created.';\nGO\n")
    return "".join(parts)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            raise SystemExit("db/mssql/igamonmeet-schema.sql is out of date: run python3 tools/db/build_mssql_script.py and commit it.")
        print("db/mssql/igamonmeet-schema.sql is up to date.")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {OUT.relative_to(ROOT)}")
